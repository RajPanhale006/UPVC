# Shivshakti UPVC — install JDK + Android SDK (no admin required)
# Run: powershell -ExecutionPolicy Bypass -File scripts/setup-android-build.ps1

$ErrorActionPreference = "Stop"

$BuildRoot = Join-Path $env:LOCALAPPDATA "ShivshaktiAndroidBuild"
$JdkDir = Join-Path $BuildRoot "jdk-21"
$SdkDir = Join-Path $env:LOCALAPPDATA "Android\Sdk"
$CmdlineToolsDir = Join-Path $SdkDir "cmdline-tools\latest"
$ProjectRoot = Split-Path $PSScriptRoot -Parent

Write-Host "=== Shivshakti Android build setup ===" -ForegroundColor Cyan
Write-Host "Build root: $BuildRoot"
Write-Host "Android SDK: $SdkDir"

New-Item -ItemType Directory -Force -Path $BuildRoot | Out-Null
New-Item -ItemType Directory -Force -Path $SdkDir | Out-Null

function Expand-Zip($ZipPath, $DestDir) {
    New-Item -ItemType Directory -Force -Path $DestDir | Out-Null
    Expand-Archive -Path $ZipPath -DestinationPath $DestDir -Force
}

# --- JDK 21 (Eclipse Temurin) — required by Capacitor Android plugins ---
if (-not (Test-Path (Join-Path $JdkDir "bin\java.exe"))) {
    Write-Host "`nDownloading JDK 21..." -ForegroundColor Yellow
    $jdkZip = Join-Path $BuildRoot "jdk-21.zip"
    $jdkUrl = "https://api.adoptium.net/v3/binary/latest/21/ga/windows/x64/jdk/hotspot/normal/eclipse?project=jdk"
    Invoke-WebRequest -Uri $jdkUrl -OutFile $jdkZip -UseBasicParsing

    $jdkExtract = Join-Path $BuildRoot "jdk-extract"
    if (Test-Path $jdkExtract) { Remove-Item $jdkExtract -Recurse -Force }
    Expand-Zip $jdkZip $jdkExtract

    $jdkFolder = Get-ChildItem $jdkExtract -Directory | Select-Object -First 1
    if (Test-Path $JdkDir) { Remove-Item $JdkDir -Recurse -Force }
    Move-Item $jdkFolder.FullName $JdkDir
    Remove-Item $jdkExtract -Recurse -Force -ErrorAction SilentlyContinue
    Remove-Item $jdkZip -Force -ErrorAction SilentlyContinue
    Write-Host "JDK 21 installed at $JdkDir" -ForegroundColor Green
} else {
    Write-Host "JDK 21 already present." -ForegroundColor Green
}

$env:JAVA_HOME = $JdkDir
$env:Path = "$JdkDir\bin;$env:Path"

# --- Android command-line tools ---
if (-not (Test-Path (Join-Path $CmdlineToolsDir "bin\sdkmanager.bat"))) {
    Write-Host "`nDownloading Android command-line tools..." -ForegroundColor Yellow
    $toolsZip = Join-Path $BuildRoot "cmdline-tools.zip"
    $toolsUrl = "https://dl.google.com/android/repository/commandlinetools-win-11076708_latest.zip"
    Invoke-WebRequest -Uri $toolsUrl -OutFile $toolsZip -UseBasicParsing

    $toolsExtract = Join-Path $BuildRoot "cmdline-tools-extract"
    if (Test-Path $toolsExtract) { Remove-Item $toolsExtract -Recurse -Force }
    Expand-Zip $toolsZip $toolsExtract

    $latestParent = Join-Path $SdkDir "cmdline-tools"
    New-Item -ItemType Directory -Force -Path $latestParent | Out-Null
    if (Test-Path $CmdlineToolsDir) { Remove-Item $CmdlineToolsDir -Recurse -Force }
    Move-Item (Join-Path $toolsExtract "cmdline-tools") $CmdlineToolsDir
    Remove-Item $toolsExtract -Recurse -Force -ErrorAction SilentlyContinue
    Remove-Item $toolsZip -Force -ErrorAction SilentlyContinue
    Write-Host "Command-line tools installed." -ForegroundColor Green
} else {
    Write-Host "Android command-line tools already present." -ForegroundColor Green
}

$env:ANDROID_HOME = $SdkDir
$env:ANDROID_SDK_ROOT = $SdkDir
$env:Path = "$CmdlineToolsDir\bin;$SdkDir\platform-tools;$env:Path"

# --- SDK packages ---
Write-Host "`nInstalling Android SDK packages (may take several minutes)..." -ForegroundColor Yellow
$sdkmanager = Join-Path $CmdlineToolsDir "bin\sdkmanager.bat"

$packages = @(
    "platform-tools",
    "platforms;android-35",
    "build-tools;35.0.0"
)

foreach ($pkg in $packages) {
    Write-Host "  -> $pkg"
    $yes = ("y`n" * 20)
    $yes | & $sdkmanager --sdk_root="$SdkDir" $pkg 2>&1 | Out-Null
}

# Accept all licenses (Gradle requires this)
$yes = ("y`n" * 50)
$yes | & $sdkmanager --sdk_root="$SdkDir" --licenses 2>&1 | Out-Null

# Capacitor may also need build-tools 34
$yes | & $sdkmanager --sdk_root="$SdkDir" "build-tools;34.0.0" 2>&1 | Out-Null

# --- local.properties for Gradle ---
$localProps = Join-Path $ProjectRoot "android\local.properties"
$escapedSdk = $SdkDir -replace '\\', '\\'
@"
## Auto-generated by scripts/setup-android-build.ps1
sdk.dir=$($SdkDir -replace '\\', '/')
"@ | Set-Content -Path $localProps -Encoding UTF8

# --- Persist env vars for current user (optional, no admin) ---
[Environment]::SetEnvironmentVariable("JAVA_HOME", $JdkDir, "User")
[Environment]::SetEnvironmentVariable("ANDROID_HOME", $SdkDir, "User")
[Environment]::SetEnvironmentVariable("ANDROID_SDK_ROOT", $SdkDir, "User")

$userPath = [Environment]::GetEnvironmentVariable("Path", "User")
$pathsToAdd = @(
    "$JdkDir\bin",
    "$CmdlineToolsDir\bin",
    "$SdkDir\platform-tools"
)
foreach ($p in $pathsToAdd) {
    if ($userPath -notlike "*$p*") {
        $userPath = "$p;$userPath"
    }
}
[Environment]::SetEnvironmentVariable("Path", $userPath, "User")

Write-Host "`n=== Setup complete ===" -ForegroundColor Green
Write-Host "JAVA_HOME=$JdkDir"
Write-Host "ANDROID_HOME=$SdkDir"
Write-Host "`nVerify:"
& "$JdkDir\bin\java.exe" -version
Write-Host "`nNext: cd to project and run  npm run build:android  then build APK (see ANDROID.md)"
